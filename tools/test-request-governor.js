'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),os=require('node:os'),path=require('node:path');
const {createGovernor}=require('../lib/request-governor');
const policy=()=>({gap:0,concurrency:2});
const ok={ok:true,status:200,json:{value:1},text:'{}'};
const wait=ms=>new Promise(resolve=>setTimeout(resolve,ms));
(async()=>{
  let sent=0,release;
  const gate=new Promise(resolve=>release=resolve);
  const g=createGovernor({policy,transport:async()=>{sent++;await gate;return ok;}});
  const readers=Array.from({length:12},()=>g.request('https://example.test/read'));
  await wait(1);assert.equal(sent,1);release();
  const values=await Promise.all(readers);assert.equal(g.snapshot().counters.joined,11);
  values[0].json.value=99;assert.equal(values[1].json.value,1,'joined consumers have independent data');
  let active=0,peak=0;
  const concurrency=createGovernor({policy,maxActive:2,transport:async()=>{active++;peak=Math.max(peak,active);await wait(4);active--;return ok;}});
  await Promise.all(Array.from({length:15},(_,i)=>concurrency.request('https://host'+i+'.test/'+i)));
  assert.equal(peak,2,'all hosts share the global concurrency ceiling');
  let now=100000,limitedCalls=0;
  const limited=createGovernor({policy,now:()=>now,transport:async()=>{limitedCalls++;return {ok:false,status:429,retryAfter:'120',json:{message:'limit'}};}});
  await limited.request('https://api.test/a');
  assert.equal((await limited.request('https://api.test/b')).status,429);assert.equal(limitedCalls,1,'host cooldown covers different endpoints');
  now+=120001;await limited.request('https://api.test/b');assert.equal(limitedCalls,2);
  const rpc=createGovernor({policy,transport:async()=>({ok:true,status:200,json:{error:{code:-32005,message:'rate limit'}}})});
  assert.equal((await rpc.request('https://rpc.test/',{method:'POST',body:{method:'eth_call',id:1}})).status,429);
  assert(rpc.snapshot().providers[0].cooldownUntil,'RPC errors trigger shared backoff');
  let pausedCalls=0,finish;
  const paused=createGovernor({policy,maxActive:1,transport:async()=>{pausedCalls++;await new Promise(r=>finish=r);return ok;}});
  const first=paused.request('https://pause.test/1');await wait(1);
  const queued=paused.request('https://pause.test/2');
  paused.setPaused(true);assert.equal((await queued).code,'REQUESTS_PAUSED');finish();await first;
  assert.equal(pausedCalls,1,'pause drains queued work without dispatch');
  assert.equal((await paused.request('https://pause.test/3')).code,'REQUESTS_PAUSED');
  const tmp=fs.mkdtempSync(path.join(os.tmpdir(),'radar-request-tests-'));
  const file=path.join(tmp,'budget.json');
  try {
    let clock=1000000,count=0;
    const args={file,policy,now:()=>clock,quoteLimit:2,windowMs:1000,transport:async()=>{count++;return ok;}};
    const budget=createGovernor(args);
    await budget.request('https://li.quest/v1/quote?amount=1');
    await budget.request('https://li.quest/v1/quote?amount=2');
    assert.equal((await budget.request('https://li.quest/v1/quote?amount=3')).code,'LOCAL_QUOTE_BUDGET');assert.equal(count,2);
    const restarted=createGovernor(args);assert.equal(restarted.quoteBudget().remaining,0,'restart preserves rolling quota');
    clock+=1001;assert.equal((await restarted.request('https://li.quest/v1/quote?amount=4')).ok,true);
    restarted.setPaused(true);assert.equal(createGovernor(args).isPaused(),true,'restart preserves global pause');
  } finally {fs.rmSync(tmp,{recursive:true,force:true});}
  let retryCalls=0;
  const reset=createGovernor({policy,transport:async()=>{retryCalls++;return {ok:false,status:429,rateLimitReset:'300',retryAfter:'30',json:{}};}});
  const response=await reset.request('https://reset.test/1');
  assert(Number(response.retryAfter)>=299,'longer server reset wins');
  console.log('PASS shared reads, response isolation, global concurrency, host/RPC cooldown, queued pause, persistent budget/pause and reset headers');
})().catch(e=>{console.error(e);process.exitCode=1});
