interface I18nContextType {
  locale: Locale;
  toggleLocale: () => void;
  t: (key: keyof typeof DICT['zh']) => string;
}

const I18nContext = createContext<I18nContextType>({
  locale: 'zh',
  toggleLocale: () => {},
  t: (key) => DICT.zh[key] || key,
});

export const I18nProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [locale, setLocale] = useState<Locale>(() => {
    const saved = localStorage.getItem('bar_locale');
    return (saved === 'zh' || saved === 'en') ? saved : 'zh';
  });

  useEffect(() => {
    localStorage.setItem('bar_locale', locale);
  }, [locale]);

  const toggleLocale = () => {
    setLocale((prev) => (prev === 'zh' ? 'en' : 'zh'));
  };

  const t = (key: keyof typeof DICT['zh']): string => {
    return DICT[locale]?.[key] || DICT.zh[key] || String(key);
  };

  return (
    <I18nContext.Provider value={{ locale, toggleLocale, t }}>
      {children}
    </I18nContext.Provider>
  );
};

export const useI18n = () => useContext(I18nContext);
